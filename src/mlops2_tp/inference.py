import json

import boto3
import pandas as pd


DATA_BUCKET = "data"
DATA_INFO_KEY = "data_info/data.json"


def load_data_dictionary():
    """
    Load preprocessing information generated by the ETL from MinIO.
    """

    s3 = boto3.client("s3")

    response = s3.get_object(
        Bucket=DATA_BUCKET,
        Key=DATA_INFO_KEY,
    )

    data_dictionary = json.loads(
        response["Body"].read().decode("utf-8")
    )

    return data_dictionary


def prepare_features(features: dict, data_dictionary: dict):
    """
    Prepare input features using the same preprocessing
    information generated during training.
    """

    columns = data_dictionary["columns"]
    median_values = data_dictionary["median_values"]

    features_df = pd.DataFrame(
        [features],
        columns=columns,
    )

    for column in columns:
        if pd.isna(features_df.loc[0, column]):
            features_df.loc[0, column] = median_values[column]

    return features_df


def predict_water_potability(
    model,
    features: dict,
    data_dictionary: dict,
):
    """
    Predict water potability.

    Returns:
        prediction: 0 = not potable, 1 = potable
        probability: probability of the positive class
    """

    features_df = prepare_features(
        features,
        data_dictionary,
    )

    prediction = int(
        model.predict(features_df)[0]
    )

    positive_class_index = list(
        model.classes_
    ).index(1)

    probability = float(
        model.predict_proba(features_df)[
            0,
            positive_class_index,
        ]
    )

    return prediction, probability